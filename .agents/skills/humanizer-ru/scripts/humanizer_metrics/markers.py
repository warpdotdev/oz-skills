def mute_by_genre(hits: list[MarkerHit], genre: str | None,
                  muted: dict[str, set[str]]) -> list[MarkerHit]:
    """Снимает маркеры, законные для жанра. Без жанра ничего не снимает:
    умолчание остаётся строгим (маркетинг и блоги, под них калибровка)."""
    names = muted.get(genre or "", set())
    return [h for h in hits if h.marker not in names and h.category not in names]


def effective_hard_bans(hits: list[MarkerHit], words: int) -> list[MarkerHit]:
    """Хард-баны после частотных порогов: то, что реально штрафуется/валит exit.

    Для маркеров из FREQ_BANS попадание остаётся баном только при двух и более
    вхождениях с плотностью выше 1 на N слов. Остальные баны проходят как есть.
    """
    out: list[MarkerHit] = []
    for h in hits:
        per = FREQ_BANS.get(h.marker)
        if per and (h.count < 2 or h.count <= words / per):
            continue
        out.append(h)
    return out


