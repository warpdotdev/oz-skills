def marker_verdict(marker_hits: list[MarkerHit]) -> str:
    """Шкала из SKILL.md: 0-2 чисто, 3-5 подозрительно, 6+ AI.
    Артефакт копипасты — однозначная улика: вердикт сразу, без шкалы."""
